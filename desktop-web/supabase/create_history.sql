-- Create Users table (Sync with Auth)
CREATE TABLE IF NOT EXISTS "public"."users" (
    "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "created_at" timestamp with time zone DEFAULT "now"() NOT NULL,
    "uuid" "text" NOT NULL UNIQUE,
    "name" "text" DEFAULT ''::"text",
    "email" "text"
);

-- Upsert User RPC (Crucial for linking Auth to Public Users)
CREATE OR REPLACE FUNCTION public.upsert_user(p_uuid text, p_email text, p_name text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  INSERT INTO public.users (uuid, email, name, created_at)
  VALUES (p_uuid, p_email, p_name, now())
  ON CONFLICT (uuid) DO UPDATE
  SET email = EXCLUDED.email,
      name = EXCLUDED.name;
END;
$$;

-- History Table
CREATE TABLE IF NOT EXISTS "public"."history" (
    "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "created_at" timestamp with time zone DEFAULT "now"() NOT NULL,
    "user_id" bigint NOT NULL REFERENCES "public"."users"("id"),
    "season" "text" NOT NULL,
    "name" "text" NOT NULL,
    "poster" "text" NOT NULL,
    "season_name" "text" NOT NULL,
    "for_to" bigint REFERENCES "public"."history"("id")
);

-- Chapters Table
CREATE TABLE IF NOT EXISTS "public"."chaps" (
    "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "created_at" timestamp with time zone DEFAULT "now"() NOT NULL,
    "history_id" bigint NOT NULL REFERENCES "public"."history"("id"),
    "cur" double precision NOT NULL,
    "dur" double precision NOT NULL,
    "name" "text" NOT NULL,
    "updated_at" timestamp with time zone NOT NULL,
    "chap_id" "text" NOT NULL
);

-- RPC: Set Progress
CREATE OR REPLACE FUNCTION "public"."set_single_progress"("p_name" "text", "p_poster" "text", "season_id" "text", "p_season_name" "text", "user_uid" "text", "e_cur" double precision, "e_dur" double precision, "e_name" "text", "e_chap" "text", "gmt" double precision DEFAULT 7) RETURNS "void"
    LANGUAGE "plpgsql"
    AS $$
DECLARE
    latest_history record;
    i_user_id int8;
    id_history_rax int8;
    id_chap int8;
BEGIN
    SELECT id INTO i_user_id FROM users WHERE uuid = user_uid LIMIT 1;
    IF i_user_id IS NULL THEN RAISE EXCEPTION 'User does not exist'; END IF;

    SELECT * INTO latest_history FROM history WHERE user_id = i_user_id AND season = season_id ORDER BY created_at DESC LIMIT 1;

    IF latest_history IS NULL OR latest_history.created_at::DATE <> (NOW() + (gmt || ' hours')::INTERVAL)::DATE THEN
        INSERT INTO history (created_at, user_id, season, name, poster, season_name)
        VALUES (NOW(), i_user_id, season_id, p_name, p_poster, p_season_name);
    END IF;

    SELECT id INTO id_history_rax FROM history WHERE user_id = i_user_id AND season = season_id ORDER BY created_at DESC LIMIT 1;

    SELECT id INTO id_chap FROM chaps WHERE history_id = id_history_rax AND chap_id = e_chap LIMIT 1;

    IF id_chap IS NULL THEN
        INSERT INTO chaps (created_at, history_id, cur, dur, name, updated_at, chap_id)
        VALUES (NOW(), id_history_rax, e_cur, e_dur, e_name, NOW(), e_chap);
    ELSE
        UPDATE chaps SET cur = e_cur, dur = e_dur, updated_at = NOW() WHERE id = id_chap;
    END IF;
END;
$$;

-- RPC: Query History
CREATE OR REPLACE FUNCTION "public"."query_history"("user_uid" "text", "page" integer, "size" integer) RETURNS TABLE("created_at" timestamp with time zone, "season" "text", "name" "text", "poster" "text", "season_name" "text", "watch_updated_at" timestamp with time zone, "watch_name" "text", "watch_id" "text", "watch_cur" double precision, "watch_dur" double precision)
    LANGUAGE "plpgsql"
    AS $$
DECLARE
    query_limit integer;
BEGIN
    query_limit := LEAST(size, 50);
    RETURN QUERY
    SELECT h.created_at, h.season, h.name, h.poster, h.season_name,
    c.updated_at as watch_updated_at, c.name as watch_name, c.chap_id as watch_id, c.cur as watch_cur, c.dur as watch_dur
    FROM public.history h
    JOIN public.users u ON h.user_id = u.id
    JOIN LATERAL (
        SELECT * FROM public.chaps WHERE history_id = h.id ORDER BY updated_at DESC LIMIT 1
    ) c ON true
    WHERE u.uuid = user_uid
    ORDER BY h.created_at DESC
    LIMIT query_limit OFFSET (page - 1) * query_limit;
END;
$$;

-- RPC: Get Last Chap
CREATE OR REPLACE FUNCTION "public"."get_last_chap"("user_uid" "text", "season_id" "text") RETURNS TABLE("created_at" timestamp with time zone, "cur" double precision, "dur" double precision, "name" "text", "chap_id" "text", "updated_at" timestamp with time zone)
    LANGUAGE "plpgsql"
    AS $$
BEGIN
    RETURN QUERY
    SELECT c.created_at, c.cur, c.dur, c.name, c.chap_id, c.updated_at
    FROM public.chaps c
    JOIN public.history h ON c.history_id = h.id
    JOIN public.users u ON h.user_id = u.id
    WHERE u.uuid = user_uid
    AND h.season = season_id
    order by updated_at desc
    limit 1;
END;
$$;

-- RPC: Get Watch Progress (Full Season)
CREATE OR REPLACE FUNCTION "public"."get_watch_progress"("user_uid" "text", "season_id" "text") RETURNS TABLE("created_at" timestamp with time zone, "cur" double precision, "dur" double precision, "name" "text", "updated_at" timestamp with time zone, "chap_id" "text")
    LANGUAGE "plpgsql"
    AS $$
BEGIN
    RETURN QUERY
   SELECT c.created_at, c.cur, c.dur, c.name, c.updated_at, c.chap_id
    FROM chaps c
    JOIN public.history h ON c.history_id = h.id
    JOIN public.users u ON h.user_id = u.id
    WHERE u.uuid = user_uid AND h.season = season_id
    ORDER BY h.id;
END;
$$;

-- RPC: Get Single Progress
CREATE OR REPLACE FUNCTION "public"."get_single_progress"("user_uid" "text", "season_id" "text", "p_chap_id" "text") RETURNS TABLE("created_at" timestamp with time zone, "cur" double precision, "dur" double precision, "name" "text", "updated_at" timestamp with time zone)
    LANGUAGE "plpgsql"
    AS $$
BEGIN
    RETURN QUERY
    SELECT c.created_at, c.cur, c.dur, c.name, c.updated_at
    FROM public.chaps c
    JOIN public.history h ON c.history_id = h.id
    JOIN public.users u ON h.user_id = u.id
    WHERE u.uuid = user_uid
    AND h.season = season_id
    AND c.chap_id = p_chap_id
    limit 1;
END;
$$;

